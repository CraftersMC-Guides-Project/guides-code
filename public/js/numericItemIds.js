function getItemNameFromNumericId(id) {
  if (id === null || id === undefined) return "Unknown Item";
  const str = String(id).trim();
  return MINECRAFT_NUMERIC_IDS[str] || MINECRAFT_NUMERIC_IDS[parseInt(str, 10)] || "Unknown Item";
}

function resolveItemName(id, damage = 0) {
  const name = getItemNameFromNumericId(id);
  return name !== "Unknown Item" ? name : String(id);
}

